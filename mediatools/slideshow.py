import os
import sys
import yaml
from mediatools import log
import mediatools.utilities as util
import mediatools.videofile as video
import utilities.file as fil


def read_yaml(yaml_file: str) -> tuple[str | None, list[dict]]:
    """Reads a slide show description file, as generated by a previous slideshow: returns the (output file, photos) tuple.
    The relative paths of the photos are relative to the folder of the YAML file, unless they exist from the current folder"""
    with open(yaml_file, encoding="utf-8") as f:
        content = yaml.safe_load(f)
    if not isinstance(content, dict) or not isinstance(content.get("photos"), list) or not content["photos"]:
        raise ValueError(f"{yaml_file} must contain a non empty 'photos' list")
    folder = os.path.dirname(os.path.abspath(yaml_file))
    photos = []
    for entry in content["photos"]:
        photo = {"photo": entry} if isinstance(entry, str) else dict(entry)
        if not photo.get("photo"):
            raise ValueError(f"Missing 'photo' in an entry of {yaml_file}")
        if not os.path.isabs(photo["photo"]) and not os.path.exists(photo["photo"]):
            photo["photo"] = os.path.join(folder, photo["photo"])
        photos.append(photo)
    return content.get("output"), photos


def main():
    parser = util.get_common_args("slideshow", "Creates a high quality video slide show from a set of photos", inputs_required=False)
    parser.add_argument("-y", "--yaml", required=False, help="YAML file describing the slides (same format as the file generated by a slide show)")
    kwargs = util.parse_media_args(parser, input_type=fil.FileType.IMAGE_FILE)

    descriptions = None
    outfile = kwargs.get("outputfile")
    if kwargs.get("yaml"):
        try:
            yaml_output, descriptions = read_yaml(kwargs["yaml"])
        except (OSError, ValueError, yaml.YAMLError) as e:
            log.logger.error("Can't read %s: %s", kwargs["yaml"], e)
            sys.exit(1)
        outfile = outfile or yaml_output
        kwargs["inputfiles"] = []
    elif not kwargs.get("inputfiles"):
        parser.error("-i or -y is required")

    output, operations = video.slideshow(
        *kwargs["inputfiles"], outfile=outfile, resolution=kwargs.get("resolution"), hw_accel=kwargs.get("hw_accel", "auto"), descriptions=descriptions
    )

    yaml_file = fil.strip_extension(output) + ".yaml"
    with open(yaml_file, "w", encoding="utf-8") as f:
        yaml.safe_dump({"output": output, "photos": operations}, f, sort_keys=False, default_flow_style=False)

    log.logger.info("Slide show description written to %s", yaml_file)
    util.generated_file(output)


if __name__ == "__main__":
    main()
