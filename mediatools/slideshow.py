import os
import sys
from pathlib import Path
import yaml
from mediatools import log
import mediatools.media_config as conf
import mediatools.options as opt
import mediatools.resolution as res
import mediatools.utilities as util
import mediatools.videofile as video
import utilities.file as fil


def read_yaml(yaml_file: str) -> tuple[dict, list[dict]]:
    """Reads a slide show description file, as generated by a previous slideshow: returns the (global parameters, photos) tuple.
    The global parameters (output, resolution) are in the "slideshow" section (the "output" at the root is also accepted).
    The relative paths of the photos are relative to the folder of the YAML file, unless they exist from the current folder"""
    with open(yaml_file, encoding="utf-8") as f:
        content = yaml.safe_load(f)
    if not isinstance(content, dict) or not isinstance(content.get("photos"), list) or not content["photos"]:
        raise ValueError(f"{yaml_file} must contain a non empty 'photos' list")
    folder = os.path.dirname(os.path.abspath(yaml_file))
    photos = []
    for entry in content["photos"]:
        photo = {"photo": entry} if isinstance(entry, str) else dict(entry)
        if not photo.get("photo"):
            raise ValueError(f"Missing 'photo' in an entry of {yaml_file}")
        if not Path(photo["photo"]).is_absolute() and not os.path.exists(photo["photo"]):
            photo["photo"] = os.path.join(folder, photo["photo"])
        photos.append(photo)
    params = content.get("slideshow") or {}
    if not isinstance(params, dict):
        raise TypeError(f"'slideshow' must be a section of parameters in {yaml_file}")
    params = {"output": content.get("output"), **params}
    if params["output"] and not Path(params["output"]).is_absolute():
        params["output"] = os.path.join(folder, params["output"])
    return params, photos


def relative_path(path: str, folder: str) -> str:
    """Returns the path relative to the folder (with / separators), or the absolute path if it can't be relative (other drive)"""
    try:
        return os.path.relpath(path, folder).replace(os.sep, "/")
    except ValueError:
        return os.path.abspath(path)


def fps_number(fps: float | str) -> int | float:
    """The frame rate as a number, an integer if it is one (50 and not 50.0)"""
    value = float(fps)
    return int(value) if value == int(value) else value


def main() -> None:
    parser = util.get_common_args("slideshow", "Creates a high quality video slide show from a set of photos", inputs_required=False)
    parser.add_argument("-y", "--yaml", required=False, help="YAML file describing the slides (same format as the file generated by a slide show)")
    parser.add_argument(
        "-r",
        "--fps",
        required=False,
        help=f"Frame rate of the video (default: {conf.get_property(conf.SLIDESHOW_FPS_KEY) or conf.DEFAULT_SLIDESHOW_FPS})",
    )
    video.add_quality_arg(parser)
    kwargs = util.parse_media_args(parser, input_type=fil.FileType.IMAGE_FILE)

    descriptions = None
    outfile = kwargs.get(util.OUTPUT_FILE)
    resolution = kwargs.get("resolution")
    fps = kwargs.get("fps")
    quality = kwargs.get("quality")
    if kwargs.get("yaml"):
        try:
            params, descriptions = read_yaml(kwargs["yaml"])
        except (OSError, ValueError, TypeError, yaml.YAMLError) as e:
            log.logger.error("Can't read %s: %s", kwargs["yaml"], e)
            sys.exit(1)
        outfile = outfile or params.get("output")
        resolution = resolution or params.get("resolution")
        fps = fps or params.get("fps")
        quality = quality or params.get("quality")
        kwargs[util.INPUT_FILES] = []
    elif not kwargs.get(util.INPUT_FILES):
        parser.error("-i or -y is required")

    resolution = res.canonical(resolution or conf.get_property(conf.SLIDESHOW_RESOLUTION_KEY))
    fps = fps or conf.get_property(conf.SLIDESHOW_FPS_KEY) or conf.DEFAULT_SLIDESHOW_FPS
    try:
        if float(fps) <= 0:
            raise ValueError
    except ValueError:
        parser.error(f"invalid fps '{fps}': it must be a positive number")
    quality = str(quality or opt.DEFAULT_QUALITY).lower()
    if quality not in opt.QUALITY_LEVELS:
        parser.error(f"invalid quality '{quality}': it must be one of {', '.join(opt.QUALITY_LEVELS)}")

    output, operations = video.slideshow(
        *kwargs[util.INPUT_FILES],
        outfile=outfile,
        resolution=resolution,
        hw_accel=kwargs.get("hw_accel", "auto"),
        descriptions=descriptions,
        fps=fps,
        quality=quality,
    )

    # The paths in the YAML file are relative to the folder of the YAML file
    yaml_file = fil.strip_extension(output) + ".yaml"
    folder = os.path.dirname(os.path.abspath(yaml_file))
    photos = [{k: relative_path(v, folder) if k in ("photo", "output") else v for k, v in op.items()} for op in operations]
    with open(yaml_file, "w", encoding="utf-8") as f:
        yaml.safe_dump(
            {
                "slideshow": {"output": relative_path(output, folder), "resolution": resolution, "fps": fps_number(fps), "quality": quality},
                "photos": photos,
            },
            f,
            sort_keys=False,
            default_flow_style=False,
        )

    log.logger.info("Slide show description written to %s", yaml_file)
    util.generated_file(output)


if __name__ == "__main__":
    main()
