# This script builds a poster of several input images
# arranged in columns, each column being a vertical stack
# of images scaled to the column's own width
# It requires availability of ffmpeg

"""Tool that creates a poster from images"""

import argparse
import os
import sys
from pathlib import Path

import yaml

import mediatools.imagefile as image
import mediatools.utilities as util
import utilities.file as fil
from mediatools import log

USAGE = "image-poster [--background_color black|white] [--gutter <px or %>] [--extra_margin_top <px>] [--extra_margin_bottom <px>] \
[--orientation portrait|landscape] [--aspect_ratio <W/H or W:H>] [--layout <rows>x<cols>] [-g 0-4] file1 file2 ... filen"

is_yaml = fil.is_yaml
relative_path = fil.relative_path


def load_yaml(yaml_file: str) -> dict:
    """Returns the content of a poster description file, as a dictionary"""
    with open(yaml_file, encoding="utf-8") as f:
        content = yaml.safe_load(f)
    if not isinstance(content, dict):
        raise TypeError(f"{yaml_file} must contain a 'columns' list")
    return content


def read_yaml(yaml_file: str) -> tuple[dict, list[dict]]:
    """Reads a poster description file, as generated by a previous poster: returns the (global parameters, columns) tuple.
    The global parameters (output, rows, columns, background_color, gutter, extra_margin_top, extra_margin_bottom, orientation,
    aspect_ratio) are in the "poster" section (the "output" at the root is also accepted). Each entry of the "columns" list has a
    width (a percentage of the poster's content width) and a list of images. The paths of the images and of the output are relative
    to the folder of the YAML file, unless they exist from the current folder"""
    content = load_yaml(yaml_file)
    if not isinstance(content.get("columns"), list) or not content["columns"]:
        raise ValueError(f"{yaml_file} must contain a non empty 'columns' list")
    folder = os.path.dirname(os.path.abspath(yaml_file))
    columns = []
    for entry in content["columns"]:
        if not isinstance(entry, dict) or not entry.get("images"):
            raise ValueError(f"Missing or empty 'images' in a column of {yaml_file}")
        images = [img if Path(img).is_absolute() or os.path.exists(img) else os.path.join(folder, img) for img in entry["images"]]
        columns.append({"width": entry.get("width"), "images": images})
    params = content.get("poster") or {}
    if not isinstance(params, dict):
        raise TypeError(f"'poster' must be a section of parameters in {yaml_file}")
    params = {"output": content.get("output"), **params}
    if params["output"] and not Path(params["output"]).is_absolute():
        params["output"] = os.path.join(folder, params["output"])
    return params, columns


def write_yaml(yaml_file: str, output: str, parameters: dict, columns: list[dict], previous: dict | None = None) -> None:
    """Writes the description of a poster: its global parameters (the generated image is the output), then its columns (the width of
    each column and the list of its images). The paths are relative to the folder of the YAML file. The other items of the previous
    content of the file are kept"""
    folder = os.path.dirname(os.path.abspath(yaml_file))
    out_columns = [{"width": col["width"], "images": [relative_path(img, folder) for img in col["images"]]} for col in columns]
    others = {k: v for k, v in (previous or {}).items() if k not in ("output", "poster", "columns")}
    content = {"poster": {"output": relative_path(output, folder), **parameters}, "columns": out_columns, **others}
    with open(yaml_file, "w", encoding="utf-8") as f:
        yaml.safe_dump(content, f, sort_keys=False, default_flow_style=False)


def __add_poster_args__(parser: argparse.ArgumentParser) -> None:
    """Adds the options of the poster tool (besides the common -i/-o/-v/--hw_accel ones) to the parser"""
    parser.add_argument("-y", "--yaml", required=False, help="Same as giving the YAML file in -i")
    parser.add_argument("-b", "--background_color", required=False, choices=["black", "white"], help="Background color of the gutter")
    parser.add_argument(
        "--gutter",
        required=False,
        help="Gutter between the images: a number of pixels (eg 64px), or a percentage of the top-left image's width (eg 5%%). Default: 80px",
    )
    parser.add_argument("--extra_margin_top", required=False, type=int, help="Extra margin (pixels) above the images, eg for a title")
    parser.add_argument("--extra_margin_bottom", required=False, type=int, help="Extra margin (pixels) below the images")
    parser.add_argument(
        "--orientation",
        required=False,
        choices=["portrait", "landscape"],
        help="Orientation of the poster (no YAML file, no --aspect_ratio/--layout): default picks whichever of the 2 standard "
        "printing formats (70/50 or 50/70) best fits the images",
    )
    parser.add_argument(
        "--aspect_ratio",
        required=False,
        help="Target aspect ratio of the poster (no YAML file, no --layout), eg 4/3, 16:9 or 1.3333. Default: 70/50, the most "
        "common poster printing format",
    )
    parser.add_argument("-l", "--layout", required=False, help="Layout of the images: rows x columns, eg 2x3")


def __resolve_poster_input__(parser: argparse.ArgumentParser, kwargs: dict) -> tuple[dict, list[dict] | None, dict | None, str | None, list[str]]:
    """Resolves -i/-y into (params, columns, previous, yaml_file, photos): reads the YAML file when one is given (columns is None
    otherwise, to be built by auto_poster_columns). Exits (via parser.error or sys.exit) on an invalid input"""
    inputs = kwargs.get(util.INPUT_FILES) or []
    yaml_files = ([kwargs["yaml"]] if kwargs.get("yaml") else []) + [f for f in inputs if is_yaml(f)]
    photos = [f for f in inputs if not is_yaml(f)]
    if len(yaml_files) > 1:
        parser.error(f"only one YAML file is accepted, got {', '.join(yaml_files)}")
    if not yaml_files and not photos:
        parser.error("-i is required")

    params: dict = {}
    previous = None
    columns = None
    yaml_file = yaml_files[0] if yaml_files else None
    if yaml_file:
        try:
            params, columns = read_yaml(yaml_file)
            previous = load_yaml(yaml_file)
        except (OSError, ValueError, TypeError, yaml.YAMLError) as e:
            log.logger.error("Can't read %s: %s", yaml_file, e)
            sys.exit(1)
    return params, columns, previous, yaml_file, photos


def __poster_settings__(kwargs: dict, params: dict) -> dict:
    """Returns the poster's settings merged from the command line (kwargs) and the YAML file (params), the former taking precedence"""
    return {
        "background_color": kwargs.get("background_color") or params.get("background_color") or "black",
        "gutter": kwargs.get("gutter", params.get("gutter", 80)),
        "extra_margin_top": kwargs.get("extra_margin_top", params.get("extra_margin_top", 0)),
        "extra_margin_bottom": kwargs.get("extra_margin_bottom", params.get("extra_margin_bottom", 0)),
        "orientation": kwargs.get("orientation") or params.get("orientation"),
        "aspect_ratio": kwargs.get("aspect_ratio") or params.get("aspect_ratio"),
        "layout": kwargs.get("layout") or params.get("layout"),
    }


def main() -> None:
    """Creates a poster from images and/or from the YAML file that describes it, and writes the YAML file that describes it"""
    util.init("image-poster")
    parser = argparse.ArgumentParser(description="Creates a mosaic of images for posters")
    util.add_input_args(parser, "Images, directories and/or one YAML file describing the poster", required=False)
    util.add_output_args(parser, "Output file to generate")
    util.add_verbosity_arg(parser)
    util.add_hw_accel_arg(parser)
    __add_poster_args__(parser)
    kwargs = util.parse_media_args(parser, input_type=fil.FileType.IMAGE_FILE)

    params, columns, previous, yaml_file, photos = __resolve_poster_input__(parser, kwargs)
    settings = __poster_settings__(kwargs, params)

    if columns is None:
        auto_kwargs = {k: settings[k] for k in ("orientation", "aspect_ratio", "layout") if settings[k]}
        columns = image.auto_poster_columns(*photos, **auto_kwargs)
    elif photos:
        columns = image.append_to_columns(columns, *photos)

    outfile = kwargs.get(util.OUTPUT_FILE) or params.get("output")
    if yaml_file and not outfile:
        outfile = f"{fil.strip_extension(yaml_file)}.jpg"

    output = image.posterize_columns(
        columns,
        out_file=outfile,
        background_color=settings["background_color"],
        gutter=settings["gutter"],
        extra_margin_top=settings["extra_margin_top"],
        extra_margin_bottom=settings["extra_margin_bottom"],
    )

    # The description is written in the input YAML file (updated with the added photos), or else next to the poster
    yaml_file = yaml_file or fil.strip_extension(output) + ".yaml"
    rows_count, cols_count = image.poster_rows_and_columns(columns)
    yaml_settings = {"rows": rows_count, "columns": cols_count, **{k: v for k, v in settings.items() if k != "layout"}}
    yaml_settings = {k: v for k, v in yaml_settings.items() if v}
    write_yaml(yaml_file, params.get("output") or output, yaml_settings, columns, previous)
    log.logger.info("Poster description written to %s", yaml_file)
    util.generated_file(output)


if __name__ == "__main__":
    main()
